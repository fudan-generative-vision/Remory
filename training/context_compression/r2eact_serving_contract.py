def default_r2eact_compressor_served_model_name(compression_ratio: int) -> str:
    """Return the canonical served-model alias for a validated ratio."""

    # Delegate validation so the canonical and compatibility entry points
    # reject exactly the same invalid ratios.
    _legacy.default_grepseek_compressor_served_model_name(compression_ratio)
    return f"{R2EACT_COMPRESSOR_SERVED_MODEL_PREFIX}{int(compression_ratio)}"


def resolve_r2eact_checkpoint_serving_contract(
    config: Mapping[str, Any],
) -> R2EActCheckpointServingContract:
    """Resolve old and current checkpoints through the established classifier."""

    return _legacy.resolve_grepseek_checkpoint_serving_contract(config)


def resolve_r2eact_live_data_paths(
    saved_args: Mapping[str, Any],
    prepared_override: Optional[str | Path] = None,
    raw_override: Optional[str | Path] = None,
) -> ResolvedR2EActLiveData:
    """Resolve live data without changing the persisted checkpoint ABI."""

    return _legacy.resolve_grepseek_live_data_paths(
        saved_args,
        prepared_override=prepared_override,
        raw_override=raw_override,
    )


